type TranslationContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
};

const TranslationContext = createContext<TranslationContextValue | null>(null);

function detectLanguage(): Language {
  const preferences = navigator.languages?.length ? navigator.languages : [navigator.language];
  const preferred = preferences.find((preference) => /^(de|en)(-|$)/i.test(preference));
  return preferred?.toLowerCase().startsWith("de") ? "de" : "en";
}

function getInitialLanguage(): Language {
  try {
    const saved = window.localStorage.getItem("elplan-language");
    if (saved === "en" || saved === "de") return saved;
  } catch {
    // The browser may disable local storage; browser preferences still provide a default.
  }
  return detectLanguage();
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage);
  const setLanguage = (next: Language) => {
    setLanguageState(next);
    try {
      window.localStorage.setItem("elplan-language", next);
    } catch {
      // Keep the selection active for this session when persistence is unavailable.
    }
  };
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo<TranslationContextValue>(() => ({
    language,
    setLanguage,
    t: (key, values = {}) => {
      let translated = language === "de" ? translations[key] ?? key : key;
      for (const [name, replacement] of Object.entries(values)) {
        translated = translated.split(`{{${name}}}`).join(String(replacement));
      }
      return translated;
    },
  }), [language]);
  return <TranslationContext.Provider value={value}>{children}</TranslationContext.Provider>;
}

export function useI18n() {
  const value = useContext(TranslationContext);
  if (!value) throw new Error("useI18n must be used within I18nProvider");
  return value;
}

export function LanguageSelect() {
  const { language, setLanguage, t } = useI18n();
  return (
    <label className="language-select">
      <span className="sr-only">{t("Language")}</span>
      <select aria-label={t("Language")} value={language} onChange={(event) => setLanguage(event.target.value as Language)}>
        <option value="en">English</option>
        <option value="de">Deutsch</option>
      </select>
    </label>
  );
}
